// Names ktrans knows without a declaration, read from the binary environment files (.ev) in a
// WinOLPC support folder. The KAREL manual: "Environment files contain definitions for
// predefined constants, ports, types, system variables, and built-ins" and every .ev is
// loaded on the controller - so a program may use TSK_STATUS, ATR_IA or KY_PREV bare.
// The undeclared check needs them all, or it reports names ktrans compiles happily.
//
//   node scripts/import-karel-ev.mjs ["C:/Program Files (x86)/FANUC/WinOLPC/Versions/V940-1/support"]
//   -> packages/fanuc/src/karel/evNames.ts
//
// Record layout seen in the files: NAME \0, a 2-byte kind, then for a constant (kind 0x0010)
// a 4-byte value straight before the next NAME. A value whose last byte is a capital letter
// runs into the next name ("EKY_PREV"); that letter is dropped when it sits where the value is.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2] ?? 'C:/Program Files (x86)/FANUC/WinOLPC/Versions/V940-1/support';
const names = new Set();
const files = readdirSync(dir).filter(f => /\.ev$/i.test(f));
/** %ENVIRONMENT names: the file name, and the name a file gives itself (core.ev is PBCORE) */
const envs = new Set(files.map(f => f.replace(/\.ev$/i, '').toUpperCase()));
for (const f of files) {
  const b = readFileSync(path.join(dir, f));
  const s = b.toString('latin1');
  const self = /^\0[\s\S]([A-Z][A-Z0-9_]+)\0/.exec(s);
  if (self) envs.add(self[1]);
  for (const m of s.matchAll(/[A-Z][A-Z0-9_$]{1,36}(?=\0)/g)) {
    const k = m.index;
    const glued = k >= 6 && b[k - 4] === 0x10 && b[k - 5] === 0 && b[k - 6] === 0;
    const name = glued ? m[0].slice(1) : m[0];
    if (name.length >= 2 && !name.startsWith('$')) names.add(name);
  }
}
const list = [...names].sort();
const out = `// Generated by scripts/import-karel-ev.mjs from ${path.basename(path.dirname(dir))} - do not edit.
// Every name the KAREL environment files (.ev) define: constants, built-ins, types and ports that
// a program uses without declaring them. Only the undeclared-name check reads this.
export const KAREL_EV_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(list.join(' '))}.split(' '));
// The environment files themselves (%ENVIRONMENT <name>): a program that loads one not listed here
// uses names this extension cannot know, so the undeclared check leaves it alone.
export const KAREL_EV_FILES: ReadonlySet<string> = new Set(${JSON.stringify([...envs].sort().join(' '))}.split(' '));
`;
writeFileSync(path.join(root, 'packages', 'fanuc', 'src', 'karel', 'evNames.ts'), out);
console.log(`${list.length} names from ${dir}`);
